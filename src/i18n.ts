export const STRINGS = { en, el };
export type MessageKey = keyof typeof en;

export function t(lang: UiLanguage, key: MessageKey): string {
  return STRINGS[lang][key];
}

export function labelName(lang: UiLanguage, label: Label): string {
  const key = label.toLowerCase() as MessageKey;
  return t(lang, key);
}

export function labelHelp(lang: UiLanguage, label: Label): string {
  const map: Record<Label, MessageKey> = {
    True: "helpTrue",
    False: "helpFalse",
    Misleading: "helpMisleading",
    Unverifiable: "helpUnverifiable",
    Opinion: "helpOpinion",
    Rhetorical: "helpRhetorical",
  };
  return t(lang, map[label]);
}

export function detectedName(lang: UiLanguage, code: "en" | "el" | "other"): string {
  if (code === "el") return t(lang, "langEl");
  if (code === "en") return t(lang, "langEn");
  return t(lang, "otherLang");
}
